"""Structured Cognitive Intelligence Loop for FRIDAY Agent.

Architecture:
UNDERSTAND -> CLARIFY -> PLAN -> CHECK PLAN -> AUTHORIZE -> EXECUTE -> OBSERVE -> VERIFY -> LEARN -> COMPLETE

Core Capabilities:
- Confidence calibration across all cognitive phases (understanding, planning, perception, tool selection, verification).
- Autonomous thresholding:
  * Lacks information -> Triggers CLARIFY with targeted questions.
  * Perception required -> Engages active screen perception pipeline.
  * Memory useful -> Queries semantic and episodic memory.
  * Tool necessary -> Determines when tools are needed vs direct answering.
  * Plan unsafe -> Flags safety hazards and enforces authorizer gating.
  * Action failed -> Dispatches evidence-based bounded recovery.
  * Strict Invariant: High confidence NEVER bypasses authorization policies.
"""

