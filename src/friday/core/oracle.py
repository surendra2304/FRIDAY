# DSN resolution
# ---------------------------------------------------------------------------
def resolve_database_url(explicit: str | None = None) -> str | None:
    """Return the configured database URL, or ``None`` when nothing is set.

    ``explicit`` wins, then the process environment. Values are stripped so an
    empty variable (a common Compose/default artifact) counts as "not set".
    """
    if explicit and explicit.strip():
        return explicit.strip()
    for key in DATABASE_URL_ENV_KEYS:
        value = os.getenv(key)
        if value and value.strip():
            return value.strip()
    return None


def is_oracle_url(url: str | None) -> bool:
    """Return True when ``url`` selects an Oracle dialect."""
    if not url:
        return False
    scheme = url.split("://", 1)[0].strip().lower()
    return scheme in _ORACLE_SCHEMES


def normalise_oracle_url(url: str) -> str:
    """Normalise any accepted Oracle URL form to ``oracle+oracledb://``.

    ``oracle://`` and ``oracle+oracledb_async://`` both appear in older config;
    SQLAlchemy 2.x exposes sync *and* async engines through the single
    ``oracle+oracledb`` dialect, so one canonical form is enough.
    """
    if not is_oracle_url(url):
        raise PersistenceConfigError(
            f"Database URL must be an Oracle DSN, got scheme '{url.split('://', 1)[0]}'."
        )
    _, _, rest = url.partition("://")
    return f"{_SYNC_DRIVER}://{rest}"


def require_database_url(explicit: str | None = None) -> str:
    """Return a validated Oracle DSN or raise ``PersistenceConfigError``.

    This is the fail-closed gate: production callers get an actionable error
    instead of a silent SQLite file.
    """
    raw = resolve_database_url(explicit)
    if not raw:
        raise PersistenceConfigError(
            "No database configured. FRIDAY persists to Oracle Autonomous Database; "
            "set DATABASE_URL (or FRIDAY_DATABASE_URL / FRIDAY_UNIVERSE_DB_URL) to an "
            "oracle+oracledb:// DSN owned by the FRIDAY schema user."
        )
    if not is_oracle_url(raw):
        raise PersistenceConfigError(
            "Configured database URL is not Oracle. FRIDAY requires an "
            f"oracle+oracledb:// DSN (got '{raw.split('://', 1)[0]}://...'). "
            "SQLite and PostgreSQL are no longer valid production backends."
        )
    return normalise_oracle_url(raw)


def ephemeral_backend_allowed() -> bool:
    """True when a non-persistent backend may be used (unit tests / test env).

    Production never qualifies: it requires ``FRIDAY_ENV=production`` and is
    validated by :func:`friday.core.startup_validator.validate_runtime_environment`.
    """
    if os.getenv("FRIDAY_ENV", "").strip().lower() in {"testing", "test"}:
        return True
    return "pytest" in sys.modules


# ---------------------------------------------------------------------------
# Engines
# ---------------------------------------------------------------------------
def get_engine(url: str | None = None, *, create_schema: bool = True) -> Engine:
    """Return a cached SQLAlchemy sync engine for the FRIDAY schema.

    The engine is created lazily so importing a module that declares a store
    singleton never opens a socket at import time. Requires ``oracledb``; the
    dependency error is surfaced as a configuration error, not an ImportError
    from deep inside a request.
    """
    dsn = require_database_url(url)
    with _ENGINE_LOCK:
        engine = _ENGINES.get(dsn)
        if engine is None:
            try:
                from sqlalchemy import create_engine
                from sqlalchemy.pool import QueuePool

                engine = create_engine(
                    dsn,
                    poolclass=QueuePool,
                    pool_pre_ping=True,
                    pool_size=5,
                    max_overflow=10,
                    pool_recycle=1800,
                    future=True,
                )
            except ModuleNotFoundError as exc:  # pragma: no cover - dependency guard
                raise PersistenceConfigError(
                    "The 'oracledb' driver is not installed in this environment; "
                    "Oracle persistence is unavailable."
                ) from exc
            except Exception as exc:
                raise PersistenceError(
                    f"Could not create the Oracle engine: {type(exc).__name__}: {exc}"
                ) from exc
            _ENGINES[dsn] = engine

    if create_schema:
        ensure_schema(engine)
    return engine


def get_async_dsn(url: str | None = None) -> str:
    """Return the DSN to hand to ``create_async_engine``.

    SQLAlchemy's ``oracle+oracledb`` dialect serves sync and async engines from
    the same URL, so this is the same normalised value; it exists so callers do
    not re-invent the ``oracledb_async`` URL that never existed.
    """
    return require_database_url(url)


def ensure_schema(engine: Engine | None = None) -> None:
    """Create every FRIDAY table/index if it is missing. Idempotent."""
    engine = engine or get_engine(create_schema=False)
    key = str(engine.url)
    if key in _SCHEMA_BOOTSTRAPPED:
        return
    with _ENGINE_LOCK:
        if key in _SCHEMA_BOOTSTRAPPED:
            return
        try:
            metadata.create_all(engine, checkfirst=True)
        except Exception as exc:
            raise PersistenceError(
                f"Oracle schema bootstrap failed: {type(exc).__name__}: {exc}"
            ) from exc
        _SCHEMA_BOOTSTRAPPED.add(key)
        logger.info("Oracle schema '%s' verified (%d tables).", SCHEMA_OWNER, len(metadata.tables))


def dispose_engines() -> None:
    """Dispose every cached engine. Used by tests and graceful shutdown."""
    with _ENGINE_LOCK:
        for engine in _ENGINES.values():
            try:
                engine.dispose()
            except Exception:  # pragma: no cover - best effort
                pass
        _ENGINES.clear()
        _SCHEMA_BOOTSTRAPPED.clear()


@contextmanager
def transaction(engine: Engine | None = None) -> Iterator[Connection]:
    """Yield a connection inside a transaction, rolling back on failure."""
    eng = engine or get_engine()
    with eng.begin() as conn:
        yield conn


# ---------------------------------------------------------------------------
# Execution helpers -- lower-cased rows, ``:name`` binds, no LIMIT
# ---------------------------------------------------------------------------
def _normalise_value(value: Any) -> Any:
    """Convert Oracle ``LOB`` values (CLOB/BLOB) into ``str``/``bytes``.

    ``python-oracledb`` hands back LOB handles for CLOB columns by default; a
    handle is not JSON-decodable, so every row passes through here first.
    """
    if value is None or isinstance(value, (str, bytes, int, float, bool)):
        return value
    read = getattr(value, "read", None)
    if callable(read):
        try:
            return read()
        except Exception:  # pragma: no cover - closed/invalid LOB
            return value
    return value


def _lower_keys(result: Any, row: Sequence[Any]) -> dict[str, Any]:
    return {str(key).lower(): _normalise_value(value) for key, value in zip(result.keys(), row)}


def query_all(
    sql: str,
    params: Mapping[str, Any] | None = None,
    *,
    engine: Engine | None = None,
) -> list[dict[str, Any]]:
    """Run a SELECT and return lower-cased dictionaries."""
    eng = engine or get_engine()
    with eng.connect() as conn:
        result = conn.execute(text(sql), dict(params or {}))
        return [_lower_keys(result, row) for row in result.fetchall()]


def query_one(
    sql: str,
    params: Mapping[str, Any] | None = None,
    *,
    engine: Engine | None = None,
) -> dict[str, Any] | None:
    """Run a SELECT returning at most one lower-cased dictionary."""
    rows = query_all(sql, params, engine=engine)
    return rows[0] if rows else None


def execute(
    sql: str,
    params: Mapping[str, Any] | None = None,
    *,
    engine: Engine | None = None,
) -> int:
    """Run a DML statement in its own transaction and return the rowcount."""
    eng = engine or get_engine()
    with eng.begin() as conn:
        result = conn.execute(text(sql), dict(params or {}))
        return int(result.rowcount or 0)


def execute_many(
    sql: str,
    rows: Sequence[Mapping[str, Any]],
    *,
    engine: Engine | None = None,
) -> int:
    """Run the same DML for many parameter sets in one transaction."""
    if not rows:
        return 0
    eng = engine or get_engine()
    with eng.begin() as conn:
        result = conn.execute(text(sql), [dict(r) for r in rows])
        return int(result.rowcount or 0)


def scalar(
    sql: str,
    params: Mapping[str, Any] | None = None,
    *,
    engine: Engine | None = None,
    default: Any = None,
) -> Any:
    """Return the first column of the first row, or ``default``."""
    row = query_one(sql, params, engine=engine)
    if not row:
        return default
    return next(iter(row.values()), default)


def health() -> dict[str, Any]:
    """Probe the configured Oracle schema without raising.

    Returns ``{"configured", "reachable", "schema", "missing_tables", "error"}``
    so readiness and doctor surfaces can report the truth instead of a
    hard-coded "healthy".
    """
    report: dict[str, Any] = {
        "configured": False,
        "backend": "oracle",
        "schema": SCHEMA_OWNER,
        "reachable": False,
        "missing_tables": [],
        "error": None,
    }
    raw = resolve_database_url()
    if not raw:
        report["error"] = "DATABASE_URL is not configured"
        return report
    report["configured"] = True
    if not is_oracle_url(raw):
        report["error"] = "DATABASE_URL is not an Oracle DSN"
        return report
    try:
        engine = get_engine(create_schema=True)
        with engine.connect() as conn:
            conn.execute(text("SELECT 1 FROM DUAL")).scalar_one()
            present = {
                str(name).lower()
                for (name,) in conn.execute(
                    text("SELECT table_name FROM user_tables")
                ).fetchall()
            }
        report["reachable"] = True
        report["missing_tables"] = sorted(set(metadata.tables) - present)
    except Exception as exc:
        report["error"] = f"{type(exc).__name__}: {exc}"
    return report


def nullif_empty(value: Any) -> Any:
    """Oracle stores ``''`` as ``NULL``; normalise explicitly at the boundary."""
    if isinstance(value, str) and value == "":
        return None
    return value


