"""Oracle Autonomous Database (26ai / 23.x) persistence primitives for FRIDAY.

Every durable FRIDAY store writes to one schema, owned by the Oracle user
``FRIDAY``. This module owns the pieces that must be identical across those
stores so the rules live in one place:

* DSN resolution and validation (:func:`resolve_database_url`). A missing or
  non-Oracle URL is a hard error for production paths -- there is no silent
  SQLite fallback. ``DATABASE_URL`` / ``FRIDAY_DATABASE_URL`` /
  ``FRIDAY_UNIVERSE_DB_URL`` are the accepted inputs and all three are
  normalised to SQLAlchemy's ``oracle+oracledb`` dialect.
* One :class:`~sqlalchemy.MetaData` describing every table FRIDAY owns, plus an
  idempotent ``create_all`` bootstrap (:func:`ensure_schema`).
* Small execution helpers that return lower-cased dictionaries, because Oracle
  folds unquoted identifiers to upper case while every caller in this codebase
  reads ``row["metadata"]``-style lower-case keys.

Oracle rules encoded here (see the module docstring of each store for usage):

* bind parameters are ``:name`` only -- never ``?``;
* row limiting is ``FETCH FIRST :n ROWS ONLY`` -- never ``LIMIT``;
* no reserved identifiers (``MODE``, ``LEVEL``, ``SIZE``, ``COMMENT``,
  ``SESSION``, ``ACCESS``, ``NUMBER``, ``DATE``, ``START``, ``END``, ``ORDER``);
* no ``INSERT OR REPLACE`` / ``ON CONFLICT`` -- use ``MERGE``;
* no ``AUTOINCREMENT`` -- use ``GENERATED BY DEFAULT AS IDENTITY``;
* JSON is ``json.dumps`` into ``CLOB``;
* an empty string is ``NULL``, so callers must not rely on ``''`` surviving.
"""

