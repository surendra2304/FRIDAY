    lifecycle_state: StrategyLifecycleState = StrategyLifecycleState.READY_FOR_REVIEW
    allocated_capital_usdt: float = 0.0
    age_days: int = 0
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


