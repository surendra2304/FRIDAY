    def get_candidate(self, name_or_id: str) -> StrategyCandidate | None:
        """Retrieves a strategy by name or candidate ID."""
        with self._lock:
            for s in self._strategies.values():
                if name_or_id.lower() in (s.name.lower(), s.candidate_id.lower()):
                    return s
            return None

    def get_latest_candidate(self) -> StrategyCandidate | None:
        """Returns the primary strategy awaiting human review."""
        with self._lock:
            for s in self._strategies.values():
                if s.lifecycle_state == StrategyLifecycleState.READY_FOR_REVIEW:
                    return s
            return list(self._strategies.values())[-1]

    def update_lifecycle_state(self, name: str, new_state: StrategyLifecycleState) -> bool:
        """Transitions a strategy to a new lifecycle state."""
        with self._lock:
            s = self.get_candidate(name)
            if not s:
                return False
            old_state = s.lifecycle_state
            s.lifecycle_state = new_state
            logger.info(f"[STRATEGY_PORTFOLIO] {s.name} transitioned: {old_state.value} -> {new_state.value}")
            return True

    def get_portfolio_overview(self) -> dict[str, Any]:
        """Returns strategy distribution across all lifecycle stages."""
        with self._lock:
            live = [s for s in self._strategies.values() if s.lifecycle_state == StrategyLifecycleState.LIVE]
            inc = [s for s in self._strategies.values() if s.lifecycle_state == StrategyLifecycleState.INCUBATION]
            cand = [s for s in self._strategies.values() if s.lifecycle_state == StrategyLifecycleState.READY_FOR_REVIEW]
            prob = [s for s in self._strategies.values() if s.lifecycle_state == StrategyLifecycleState.PROBATION]
            ret = [s for s in self._strategies.values() if s.lifecycle_state == StrategyLifecycleState.RETIRED]

            # Sort live by Sharpe ratio
            live_ranked = sorted(live, key=lambda x: x.sharpe_2y, reverse=True)

            return {
                "total_strategies_count": len(self._strategies),
                "live_count": len(live),
                "incubation_count": len(inc),
                "candidate_count": len(cand),
                "probation_count": len(prob),
                "retired_count": len(ret),
                "live_strategies_ranked": [s.__dict__ for s in live_ranked],
                "incubation_strategies": [s.__dict__ for s in inc],
                "candidates_awaiting_review": [s.__dict__ for s in cand],
            }

    def get_spoken_portfolio_summary(self) -> str:
        """Returns concise spoken overview of the strategy portfolio."""
        overview = self.get_portfolio_overview()
        top_strat = overview["live_strategies_ranked"][0] if overview["live_strategies_ranked"] else None

        top_msg = f"Top performing strategy is {top_strat['name']} with a 2-year Sharpe ratio of {top_strat['sharpe_2y']:.2f}." if top_strat else ""

        return (
            f"Strategy portfolio overview: You currently have {overview['live_count']} live strategies deployed across capital, "
            f"{overview['incubation_count']} in incubation, and {overview['candidate_count']} candidate awaiting human approval review. "
            f"{top_msg} All live strategies maintain positive track records."
        )
